"""quickstart.py — sincnn3 の使い方をひと通り試す例（CPU で 1 分ほど）

実行（リポジトリ直下で）:
    pip install -e .
    python examples/quickstart.py

試すこと:
    1. 果物の表を光の器に覚えさせる（KnowledgeBase）
    2. 順引き・逆引き・推し量り・否定・なじみ・確信度・融合・物を足す
    3. 関係をつなげてたどる（RelationChain）
    4. 出来事と時の順を 1 本の光に重ねて覚える（HolographicMemory）
"""
import sys

from sincnn3 import HolographicMemory, KnowledgeBase, Not, RelationChain, confidence

sys.stdout.reconfigure(encoding="utf-8")


def show(title, d, k=3):
    print(f"  {title}: " + "、".join(f"{name} {100 * p:.0f}%" for name, p in list(d.items())[:k]))


# ---------------------------------------------------------------------------
# 1. 物と属性の表（実験21 と同じ表。割合は持ち主の例にならって決めたもの）
# ---------------------------------------------------------------------------
TABLE = {
    "リンゴ": {"色": {"赤": .8, "緑": .2}, "大きさ": {"大": .6, "小": .4}, "形": {"丸い": 1}, "味": {"甘い": .6, "酸っぱい": .4}, "触感": {"しゃきしゃき": 1}},
    "トマト": {"色": {"赤": .9, "緑": .1}, "大きさ": {"大": .4, "小": .6}, "形": {"丸い": 1}, "味": {"甘い": .3, "酸っぱい": .7}, "触感": {"むしゃむしゃ": 1}},
    "バナナ": {"色": {"黄": 1}, "大きさ": {"大": .7, "小": .3}, "形": {"細長い": 1}, "味": {"甘い": 1}, "触感": {"ねっとり": 1}},
    "レモン": {"色": {"黄": .9, "緑": .1}, "大きさ": {"大": .2, "小": .8}, "形": {"丸い": .7, "細長い": .3}, "味": {"酸っぱい": 1}, "触感": {"しゃきしゃき": .5, "むしゃむしゃ": .5}},
    "イチゴ": {"色": {"赤": 1}, "大きさ": {"小": 1}, "形": {"丸い": .8, "細長い": .2}, "味": {"甘い": .7, "酸っぱい": .3}, "触感": {"むしゃむしゃ": 1}},
}

print("1. 学習（物ごとに 1 台の光の器）")
kb = KnowledgeBase(TABLE, seed=0)
errs = kb.fit()
print("  表との差（0 = 完全一致）: " + "、".join(f"{o} {e:.3f}" for o, e in errs.items()))

print("\n2. 引く・推し量る")
show("順引き「リンゴの色は？」", kb.lookup("リンゴ", "色"))
show("逆引き「赤いものは？」", kb.reverse("色", "赤"))
fwd, back = kb.verify_reverse("トマト", "色", "赤")
print(f"  逆向きに光を通した明るさ {back:.4f} = 順向きの明るさ {fwd:.4f}（器が光の量を保つため）")

ans = kb.infer({"形": "丸い", "色": "赤", "触感": "むしゃむしゃ", "味": "酸っぱい"})
show("推し量り「丸い赤い実をむしゃむしゃ、酸っぱかった」", ans)
print(f"  確信度 {confidence(ans):.2f}")
show("否定「赤くない、丸い」", kb.infer({"色": Not("赤"), "形": "丸い"}))

f_ok = kb.familiarity({"色": "黄", "形": "細長い"})
f_ng = kb.familiarity({"色": "赤", "形": "細長い", "触感": "ねっとり"})
print(f"  なじみ「黄色くて細長い」{f_ok:.2f}（知らない? {kb.is_unknown({'色': '黄', '形': '細長い'})}）"
      f" ／「赤くて細長くてねっとり」{f_ng:.2f}（知らない? {kb.is_unknown({'色': '赤', '形': '細長い', '触感': 'ねっとり'})}）")

kb.fuse(["リンゴ", "トマト"], [0.5, 0.5], name="リンゴとトマトの間")
show("融合「リンゴとトマトの間」の味", kb.lookup("リンゴとトマトの間", "味"))

kb.add("サクランボ", {"色": {"赤": 1}, "大きさ": {"小": 1}, "味": {"甘い": .8, "酸っぱい": .2}}, start_from="イチゴ")
show("物を足す「サクランボ」の形（表に書かず、イチゴから受け継いだ）", kb.lookup("サクランボ", "形"))

# ---------------------------------------------------------------------------
# 3. 関係をつなげてたどる
# ---------------------------------------------------------------------------
print("\n3. 関係をたどる（256 個の記号を 1 つの輪につなぎ、毎段に雑音と光の減り 7% を入れて 30 段）")
names = [f"記号{i}" for i in range(256)]
for p in (1, 2):
    ch = RelationChain(names, n=64, p=p, seed=0)
    for i in range(256):
        ch.relate(names[i], names[(i + 1) % 256])
    path = ch.follow("記号0", hops=30, noise=1.0, loss=0.93)
    ok = sum(path[h] == names[h + 1] for h in range(30))
    print(f"  p={p}（{'きれいにしない' if p == 1 else '明るさの 2 乗できれいにする'}）: 30 段のうち {ok} 段が正しい。最初の 5 段: " + " → ".join(path[:5]))

# ---------------------------------------------------------------------------
# 4. 出来事と時の順を 1 本の光に
# ---------------------------------------------------------------------------
print("\n4. ホログラフィックな記憶（浦島太郎の一部）")
mem = HolographicMemory(dim=4096, seed=0)
mem.store(0, {"主語": "浦島太郎", "述語": "助ける", "目的語": "亀"})
mem.store(1, {"主語": "亀", "述語": "連れて行く", "目的語": "浦島太郎", "行き先": "竜宮城"})
mem.store(2, {"主語": "乙姫", "述語": "渡す", "目的語": "玉手箱", "相手": "浦島太郎"})
mem.store(3, {"主語": "浦島太郎", "述語": "開ける", "目的語": "玉手箱"})
print(f"  時刻 1 の行き先は？ → {mem.recall(1, '行き先')[0]}")
print(f"  時刻 2 の目的語は？ → {mem.recall(2, '目的語')[0]}")
print(f"  「玉手箱を開ける」のはいつ？ → 時刻 {mem.find({'述語': '開ける', '目的語': '玉手箱'})}")
